from pathlib import Path

from openpyxl import Workbook

OUT = Path(__file__).resolve().parent


def save(name, rows, title_rows=()):
    wb = Workbook()
    ws = wb.active
    for t in title_rows:
        ws.append(t)
    for r in rows:
        ws.append(r)
    wb.save(OUT / name)


def hometax(kind, items):
    """홈택스 세금계산서 목록 조회 엑셀과 같은 열 배치(상단 제목행 포함)."""
    head = ["작성일자", "승인번호", "발급일자", "전송일자", "공급자사업자등록번호", "종사업장번호", "상호", "대표자명",
            "주소", "공급받는자사업자등록번호", "종사업장번호", "상호", "대표자명", "주소", "합계금액", "공급가액",
            "세액", "전자세금계산서분류", "품목명"]
    me = ("123-81-00001", "", "(주)곰마테스트", "김대표", "서울")
    rows = [head]
    for i, (d, biz, name, ceo, supply, item) in enumerate(items):
        other = (biz, "", name, ceo, "서울")
        s, b = (me, other) if kind == "매출" else (other, me)
        vat = supply // 10
        rows.append([d, f"2026{i:04d}-41000000-0000{i}", d, d, *s, *b, supply + vat, supply, vat, "세금계산서", item])
    return rows, [[f"{kind} 전자세금계산서 목록"], ["조회기간: 2026-09-01 ~ 2026-09-30"], []]


